// Ley de Planck. lambda_m en metros, T en kelvin.
static float planck_radiance(float lambda_m, float T) {
  const float c1 = 3.741771e-16f;
  const float c2 = 1.4388e-2f;
  float d = 1.0f / (expf(c2 / (lambda_m * T)) - 1.0f);
  return (c1 * powf(lambda_m, -5.0f) / (float)M_PI) * d;
}

static void blackbody_spectrum(float T, float out[PSPECTRO_N]) {
  for (int i = 0; i < PSPECTRO_N; i++) {
    float wl_nm = 380.0f + 5.0f * i;
    out[i] = planck_radiance(wl_nm * 1e-9f, T);
  }
}

static float daylight_locus(float x) {
  return -3.000f * x * x + 2.870f * x - 0.275f;
}

static void CCT_to_xy_CIE_D(float CCT, float &x, float &y) {
  float CCT2 = CCT * CCT;
  float CCT3 = CCT2 * CCT;
  if (CCT <= 7000.0f) {
    x = -4.607e9f / CCT3 + 2.9678e6f / CCT2 + 0.09911e3f / CCT + 0.244063f;
  } else {
    x = -2.0064e9f / CCT3 + 1.9018e6f / CCT2 + 0.24748e3f / CCT + 0.23704f;
  }
  y = daylight_locus(x);
}

static void d_illuminant_spectrum(float CCT, float out[PSPECTRO_N]) {
  float x, y;
  CCT_to_xy_CIE_D(CCT, x, y);
  float M = 0.0241f + 0.2562f * x - 0.7341f * y;
  float M1 = (-1.3515f - 1.7703f * x + 5.9114f * y) / M;
  float M2 = (0.0300f - 31.4424f * x + 30.0717f * y) / M;
  // redondeo a 3 decimales, segun recomendacion CIE 015:2004
  M1 = roundf(M1 * 1000.0f) / 1000.0f;
  M2 = roundf(M2 * 1000.0f) / 1000.0f;
  for (int i = 0; i < PSPECTRO_N; i++) {
    out[i] = D_ILLUM_S0[i] + M1 * D_ILLUM_S1[i] + M2 * D_ILLUM_S2[i];
  }
}

// ===========================================================================
// CRI (CIE 13.3-1995): colorimetria de las 8 muestras de color (TCS01-08)
// bajo un iluminante S, mas adaptacion cromatica y espacio CIE 1964 U*V*W*
// ===========================================================================

static const float *TCS_TABLE[8] = {
  TCS_TCS01, TCS_TCS02, TCS_TCS03, TCS_TCS04,
  TCS_TCS05, TCS_TCS06, TCS_TCS07, TCS_TCS08
};

static inline float c_term(float u, float v) { return (4.0f - u - 10.0f * v) / v; }
static inline float d_term(float u, float v) { return (1.708f * v + 0.404f - 1.481f * u) / v; }

// Calcula (U*,V*,W*) de las 8 muestras bajo el iluminante S.
// chromatic_adaptation: true para el lado "test" (adapta al punto blanco
// de referencia), false para el lado "referencia" (no necesita adaptarse
// a si mismo).
static void tcs_colorimetry(const float S[PSPECTRO_N], const float S_ref[PSPECTRO_N],
                             bool chromatic_adaptation, float UVW_out[8][3]) {
  float Xt, Yt, Zt;
  spectrum_to_XYZ(S, Xt, Yt, Zt);
  float ut, vt;
  XYZ_to_uv1960(Xt, Yt, Zt, ut, vt);

  float Xr, Yr, Zr;
  spectrum_to_XYZ(S_ref, Xr, Yr, Zr);
  float ur, vr;
  XYZ_to_uv1960(Xr, Yr, Zr, ur, vr);

  float sum_ybar_S = 0;
  for (int i = 0; i < PSPECTRO_N; i++) sum_ybar_S += S[i] * CMF_YBAR[i];

  float ct = 0, dt = 0, cr = 0, dr = 0;
  if (chromatic_adaptation) {
    ct = c_term(ut, vt); dt = d_term(ut, vt);
    cr = c_term(ur, vr); dr = d_term(ur, vr);
  }

  for (int k = 0; k < 8; k++) {
    const float *R = TCS_TABLE[k];
    float Xtcs = 0, Ytcs = 0, Ztcs = 0;
    for (int i = 0; i < PSPECTRO_N; i++) {
      float w = R[i] * S[i];
      Xtcs += w * CMF_XBAR[i];
      Ytcs += w * CMF_YBAR[i];
      Ztcs += w * CMF_ZBAR[i];
    }
    float u_tcs, v_tcs;
    XYZ_to_uv1960(Xtcs, Ytcs, Ztcs, u_tcs, v_tcs);
    float Y_norm = 100.0f * Ytcs / sum_ybar_S;

    if (chromatic_adaptation) {
      float ctcs = c_term(u_tcs, v_tcs);
      float dtcs = d_term(u_tcs, v_tcs);
      float cr_ct = cr / ct;
      float dr_dt = dr / dt;
      float denom = 16.518f + 1.481f * cr_ct * ctcs - dr_dt * dtcs;
      u_tcs = (10.872f + 0.404f * cr_ct * ctcs - 4.0f * dr_dt * dtcs) / denom;
      v_tcs = 5.52f / denom;
    }

    float W = 25.0f * cbrtf(Y_norm) - 17.0f;
    float U = 13.0f * W * (u_tcs - ur);
    float V = 13.0f * W * (v_tcs - vr);
    UVW_out[k][0] = U;
    UVW_out[k][1] = V;
    UVW_out[k][2] = W;
  }
}

// ===========================================================================
// Funcion principal
// ===========================================================================

ColorimetryResult calcular_colorimetria(const float spectrum[PSPECTRO_N]) {
  ColorimetryResult r;

  spectrum_to_XYZ(spectrum, r.X, r.Y, r.Z);
  XYZ_to_xy(r.X, r.Y, r.Z, r.x, r.y);
  XYZ_to_uv1960(r.X, r.Y, r.Z, r.u, r.v);
  r.CCT = uv_to_CCT_Robertson(r.u, r.v, r.Duv);
  r.cct_reliable = fabsf(r.Duv) <= 0.05f;

  // --- Construir el iluminante de referencia para el CRI ---
  float S_ref[PSPECTRO_N];
  if (r.CCT < 5000.0f) {
    blackbody_spectrum(r.CCT, S_ref);
  } else {
    d_illuminant_spectrum(r.CCT, S_ref);
  }

  // --- Colorimetria de las 8 muestras bajo la fuente de prueba y la referencia ---
  float UVW_test[8][3];
  float UVW_ref[8][3];
  tcs_colorimetry(spectrum, S_ref, true, UVW_test);
  tcs_colorimetry(S_ref, S_ref, false, UVW_ref);

  float sum_Ra = 0;
  for (int k = 0; k < 8; k++) {
    float dU = UVW_test[k][0] - UVW_ref[k][0];
    float dV = UVW_test[k][1] - UVW_ref[k][1];
    float dW = UVW_test[k][2] - UVW_ref[k][2];
    float dE = sqrtf(dU * dU + dV * dV + dW * dW);
    r.Ri[k] = 100.0f - 4.6f * dE;
    sum_Ra += r.Ri[k];
  }
  r.Ra = sum_Ra / 8.0f;

  return r;
}
