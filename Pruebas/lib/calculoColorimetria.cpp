void spectrum_to_XYZ(const float spectrum[PSPECTRO_N], float &X, float &Y, float &Z) {
  X = 0; Y = 0; Z = 0;
  for (int i = 0; i < PSPECTRO_N; i++) {
    X += spectrum[i] * CMF_XBAR[i];
    Y += spectrum[i] * CMF_YBAR[i];
    Z += spectrum[i] * CMF_ZBAR[i];
  }
}

void XYZ_to_xy(float X, float Y, float Z, float &x, float &y) {
  float s = X + Y + Z;
  if (s <= 0) { x = 0; y = 0; return; }
  x = X / s;
  y = Y / s;
}

void XYZ_to_uv1960(float X, float Y, float Z, float &u, float &v) {
  float U = (2.0f / 3.0f) * X;
  float V = Y;
  float W = 0.5f * (-X + 3.0f * Y + Z);
  float s = U + V + W;
  if (s <= 0) { u = 0; v = 0; return; }
  u = U / s;
  v = V / s;
}

float uv_to_CCT_Robertson(float u, float v, float &Duv) {
  float du[31], dv[31], dt[31];
  for (int i = 0; i < 31; i++) {
    float t = ROBERTSON_TABLE[i][3];
    float length = sqrtf(1.0f + t * t);
    du[i] = 1.0f / length;
    dv[i] = t / length;
  }

  int found_i = -1;
  for (int i = 1; i < 31; i++) {
    float u_i = ROBERTSON_TABLE[i][1];
    float v_i = ROBERTSON_TABLE[i][2];
    float uu = u - u_i;
    float vv = v - v_i;
    dt[i] = -uu * dv[i] + vv * du[i];
    if (dt[i] <= 0) { found_i = i; break; }
  }
  if (found_i < 0) found_i = 30;
  int i = found_i;

  float dt_current = -fminf(dt[i], 0.0f);
  float dt_previous = dt[i - 1];
  float f = (i == 1) ? 0.0f : dt_current / (dt_previous + dt_current);

  float r = ROBERTSON_TABLE[i - 1][0] * f + ROBERTSON_TABLE[i][0] * (1.0f - f);
  float T = 1.0e6f / r;

  float u_interp = ROBERTSON_TABLE[i - 1][1] * f + ROBERTSON_TABLE[i][1] * (1.0f - f);
  float v_interp = ROBERTSON_TABLE[i - 1][2] * f + ROBERTSON_TABLE[i][2] * (1.0f - f);
  float du_i = du[i] * (1.0f - f) + du[i - 1] * f;
  float dv_i = dv[i] * (1.0f - f) + dv[i - 1] * f;
  float L = sqrtf(du_i * du_i + dv_i * dv_i);
  du_i /= L;
  dv_i /= L;

  float uu = u - u_interp;
  float vv = v - v_interp;
  Duv = -(uu * du_i + vv * dv_i);

  return T;
}

