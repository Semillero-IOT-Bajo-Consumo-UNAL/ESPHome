inline float cs_integrar(const float spectrum[CS_N], const float curve[CS_N]) {
  float value = 0.0f;
  for (int i = 0; i < CS_N; i++) {
    value += spectrum[i] * curve[i] * CS_DELTA_LAMBDA_NM;
  }
  return value;
}

inline float cs_dividir_seguro(float num, float den) {
  return den != 0.0f ? num / den : 0.0f;
}

inline CircadianResult calcular_estimulo_circadiano(const float spectrum[CS_N],
                                                    float iluminancia_lx,
                                                    float duracion_h = 1.0f,
                                                    float distribucion = 1.0f) {
  float spectrum_abs[CS_N];
  const float lux_actual = 683.0f * cs_integrar(spectrum, CS_PHOTOPIC);
  const float factor_lux = cs_dividir_seguro(iluminancia_lx, lux_actual);

  for (int i = 0; i < CS_N; i++) {
    spectrum_abs[i] = spectrum[i] * factor_lux;
  }

  CircadianResult result{};
  result.melanopsin = cs_integrar(spectrum_abs, CS_MELANOPSIN);
  result.scone = cs_integrar(spectrum_abs, CS_SCONE);
  result.vlambda = cs_integrar(spectrum_abs, CS_VLAMBDA);
  result.vprime = cs_integrar(spectrum_abs, CS_VPRIME);
  result.bminusY = result.scone - 0.2616f * result.vlambda;

  const float rod_mel = 2.3f *
                        cs_dividir_seguro(result.vprime, result.vlambda + result.scone) *
                        (1.0f - std::exp(-result.vprime / 6.5215f));
  const float rod_bminusY = 1.6f *
                            cs_dividir_seguro(result.vprime, result.vlambda + 0.16f * result.scone) *
                            (1.0f - std::exp(-result.vprime / 6.5215f));

  float cs_lineal = std::max(result.melanopsin, 0.0f) - rod_mel;
  if (result.bminusY >= 0.0f) {
    cs_lineal = std::max(result.melanopsin, 0.0f) +
                std::max(0.21f * result.bminusY, 0.0f) -
                rod_bminusY - rod_mel;
  }
  cs_lineal = std::max(cs_lineal, 0.0f);

  result.CLa = 1548.0f * cs_lineal;
  result.CS = 0.7f * (1.0f - 1.0f /
      (1.0f + std::pow((result.CLa * duracion_h * distribucion) / 355.7f, 1.1026f)));

  return result;
}

